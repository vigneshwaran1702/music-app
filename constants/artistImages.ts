/**
 * Returns the true, verified high-resolution portrait image for an artist by name.
 * Prevents album covers or microphone placeholders from replacing artist faces.
 */
export function getArtistImage(artistName?: string, fallbackUrl?: string): string {
  if (!artistName || !artistName.trim()) {
    return isValidImage(fallbackUrl) ? fallbackUrl! : DEFAULT_ARTIST_AVATAR;
  }

  const clean = artistName.toLowerCase().trim();

  // 1. Exact match
  if (ARTIST_IMAGES[clean]) {
    return ARTIST_IMAGES[clean];
  }

  // 2. Multi-artist strings (e.g., "Anirudh Ravichander, Thalapathy Vijay" -> match Anirudh)
  const parts = clean.split(/[,&/|]/).map((p) => p.trim());
  for (const part of parts) {
    if (ARTIST_IMAGES[part]) {
      return ARTIST_IMAGES[part];
    }
  }

  // 3. Substring match against known keys (longest match first)
  const sortedKeys = Object.keys(ARTIST_IMAGES).sort((a, b) => b.length - a.length);
  for (const key of sortedKeys) {
    if (clean.includes(key)) {
      return ARTIST_IMAGES[key];
    }
  }

  // 4. If fallbackUrl is valid and not a known placeholder or stock image
  if (isValidImage(fallbackUrl)) {
    return fallbackUrl!;
  }

  return DEFAULT_ARTIST_AVATAR;
}

/**
 * Validates if an image URL is legitimate (not a broken or generic stock placeholder).
 */
export function isValidImage(url?: string): boolean {
  if (!url || typeof url !== 'string') return false;
  const trimmed = url.trim();
  if (!trimmed.startsWith('http')) return false;

  // Filter out the old generic unsplash microphone and default avatar placeholders
  if (trimmed.includes('photo-1511671782779')) return false;
  if (trimmed.includes('photo-1507003211169')) return false;
  if (trimmed.includes('artist-default')) return false;

  return true;
}

/**
 * Computes the correct display cover for any playlist.
 * Prioritizes custom verified cover, falls back to first track cover, then curated artwork.
 */
export function getPlaylistCover(playlist?: { coverUrl?: string; tracks?: { coverUrl?: string }[] }): string {
  if (!playlist) return DEFAULT_PLAYLIST_COVER;

  if (isValidImage(playlist.coverUrl)) {
    return playlist.coverUrl!;
  }

  if (playlist.tracks && playlist.tracks.length > 0) {
    for (const track of playlist.tracks) {
      if (isValidImage(track.coverUrl)) {
        return track.coverUrl!;
      }
    }
  }

  return DEFAULT_PLAYLIST_COVER;
}
